"""Deterministic SQL fixtures that rebuild a minimized counterexample state by hand."""

from __future__ import annotations

import math
from typing import Any

import sqlglot

from isitright.packs.sql.postgres_ddl import Schema, _ordered_schema_tables, _render_state
from isitright.packs.sql.schema import DatabaseSchema, TableSchema
from isitright.packs.sql.state import DatabaseState


def sqlite_reproducer(schema: DatabaseSchema, state: DatabaseState) -> str:
    """DDL and inserts for SQLite, without embedding either query."""
    tables = _table_order(schema, {t.name for t in state.tables})
    by_name = {t.name: t for t in state.tables}
    lines = [
        "-- Generated by isitright. Rebuilds the minimized counterexample state.",
        "PRAGMA foreign_keys = ON;",
        "BEGIN;",
        "PRAGMA defer_foreign_keys = ON;",
    ]
    lines.extend(table.ddl.rstrip().rstrip(";") + ";" for table in tables)
    for table in tables:
        lines.extend(ddl.rstrip().rstrip(";") + ";" for ddl in table.index_ddls)
    for table in tables:
        columns = [c.name for c in table.columns if c.hidden == 0]
        column_sql = ", ".join(_quote_identifier(c) for c in columns)
        for row in by_name[table.name].rows:
            values = ", ".join(_sql_literal(v) for v in row)
            lines.append(
                f"INSERT INTO {_quote_identifier(table.name)} ({column_sql}) VALUES ({values});"
            )
    lines.extend(["COMMIT;", ""])
    return "\n".join(lines)


def postgres_reproducer(
    schema: Schema,
    state: DatabaseState,
    reference_sql: str,
    candidate_sql: str,
    *,
    engine: str,
) -> str:
    """DDL, state and both programs; for DuckDB the translated SQL actually executed."""

    def translate(sql: str) -> str:
        return (
            sqlglot.transpile(sql, read="postgres", write="duckdb")[0]
            if engine == "duckdb"
            else sql
        )

    ddl = ";\n".join(translate(t.ddl) for t in _ordered_schema_tables(schema.database))
    state_sql = _render_state(schema, state)
    return (
        f"{ddl};\n{state_sql + ';' if state_sql else ''}\n"
        f"{translate(reference_sql)};\n{translate(candidate_sql)};\n"
    )


def _table_order(schema: DatabaseSchema, retained: set[str]) -> list[TableSchema]:
    pending = {t.name: t for t in schema.tables if t.name in retained}
    ordered: list[TableSchema] = []
    while pending:
        ready = sorted(
            (
                t
                for t in pending.values()
                if all(
                    fk.referenced_table not in pending or fk.referenced_table == t.name
                    for fk in t.foreign_keys
                )
            ),
            key=lambda t: t.name,
        )
        if not ready:  # Cyclic foreign keys: deterministic order; inserts may be rejected.
            ready = [pending[min(pending)]]
        for table in ready:
            ordered.append(table)
            pending.pop(table.name)
    return ordered


def _quote_identifier(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def _sql_literal(value: Any) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bytes):
        return f"X'{value.hex().upper()}'"
    if isinstance(value, str):
        return "'" + value.replace("'", "''") + "'"
    if isinstance(value, float):
        if math.isnan(value):
            return "CAST('NaN' AS REAL)"
        if math.isinf(value):
            return "(1e999)" if value > 0 else "(-1e999)"
        return repr(value)
    return str(value)
